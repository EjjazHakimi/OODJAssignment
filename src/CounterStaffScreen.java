    private void bUpdateDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bUpdateDataActionPerformed
        String newUsername = tfUsername.getText();
        String newPassword = tfPassword.getText();
        String currentPassword = tfCurrentPassword.getText();
        
        try {
            bUpdateData.setEnabled(false);
            User user = loadCurrentUser();
            
            if(currentPassword.equals(user.getPassword())) {
               user.setUsername(newUsername);
               user.setPassword(newPassword);
               
               user.toString();
               
               FileHandler fh = new FileHandler("user.txt");
               fh.updateRecord(tfCurrentID.getText().trim(), user.toString());
               
               FileHandler fh2 = new FileHandler("login.txt");
               fh2.writeLoginUserRecord(user);
               
               JOptionPane.showMessageDialog(null, "Successfully updated User Profile!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
               
               tfUsername.setText(newUsername);
               tfPassword.setText(newPassword);
               tfCurrentPassword.setText("");
               lUser.setText(newUsername);
              
            } else {
                JOptionPane.showMessageDialog(null, "Current Password is Incorrect", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } finally {
        bUpdateData.setEnabled(true);
        }
    }//GEN-LAST:event_bUpdateDataActionPerformed

    private void bCreateUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bCreateUserActionPerformed
        String newUsername = tfNewCustomerUsername.getText();
        String newPassword = tfNewCustomerPassword.getText();
        String newRole = tfNewCustomerRole.getText();
        String newID = tfNewCustomerID.getText();
        
        FileHandler fh = new FileHandler("user.txt");
        
        User u;
        
        try {
            u = dh.RegisterUser(newID, newUsername, newPassword, newRole);
            if(u == null) return;
            if(!fh.doesRecordExists(u)) {
                fh.writeRecord(u);
                dh.loadUsers();
                JOptionPane.showMessageDialog(null, "User successfully created", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
                loadUserTable();   
            } else {
                JOptionPane.showMessageDialog(null, "User already exists!", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
            
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
        tfNewCustomerUsername.setText("");
        tfNewCustomerPassword.setText("");
        tfNewCustomerID.setText("");
        
    }//GEN-LAST:event_bCreateUserActionPerformed

    private void bAssignAppointmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAssignAppointmentActionPerformed
        String appointmentID = tfAppointmentID.getText();
        String appointmentType = "";
        LocalTime appointmentEndTime = null;
        
        FileHandler fh = new FileHandler("appointment.txt");
        
        if (rbAppointmentTypeNormal.isSelected()) {
                appointmentType = "NORMAL";
            } else if (rbAppointmentTypeMajor.isSelected()) {
                appointmentType = "MAJOR";
            }
        
        if (appointmentID.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please select Appointment!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (appointmentType.equals("")) {
            JOptionPane.showMessageDialog(null, "Please select Appointment Type!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            CounterStaff counterStaff = (CounterStaff) loadCurrentUser();
            Appointment appointment = dh.getAppointmentByID(appointmentID);
            
            String technicianUsername = (String) cbAssignTechnician.getSelectedItem();
            
            Technician technician = (Technician) dh.getUserByUsername(technicianUsername);
            
            if (technician == null) {
                JOptionPane.showMessageDialog(null, "Please select a technician!", "ERROR", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            appointment.setTechnician(technician);
          
            appointmentEndTime = counterStaff.calculateEndTime(appointmentType, appointment.getAppointmentStartTime());
            
            if(!counterStaff.canAssignTechnician(technician, dh.getAppointments(), dh.getAppointmentCount(), appointment, appointmentEndTime)) {
                JOptionPane.showMessageDialog(null, "Technician is Busy!", "ERROR", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            appointment.setAppointmentType(appointmentType);
            appointment.setAppointmentStatus("ASSIGNED");
            appointment.setAppointmentPaymentStatus("UNPAID");
            appointment.setAppointmentEndTime(appointmentEndTime);
            appointment.setCounterStaff(counterStaff);
            
            
            fh.updateRecord(appointmentID, appointment.toString());
            JOptionPane.showMessageDialog(null, "Appointment successfully assigned!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
            
            tfAppointmentID.setText("");
            bgAppointmentType.clearSelection();
            
            dh.loadUsers();
            dh.loadAppointments();
            loadAppointmentTable();
            
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
       
        
    }//GEN-LAST:event_bAssignAppointmentActionPerformed

    private void bCollectPaymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bCollectPaymentActionPerformed
        FileHandler fh = new FileHandler("payment.txt");
        FileHandler fh2 = new FileHandler("appointment.txt");
        FileHandler fh3 = new FileHandler("myReceipt.txt");
        
        String paymentID = tfPaymentID.getText();
        String appointmentID = tfPayAppointmentID.getText();
        
        if(paymentID.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please Select Payment!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            CounterStaff counterStaff = (CounterStaff) loadCurrentUser();
            Payment payment = dh.getPaymentByID(paymentID);
            Appointment appointment = dh.getAppointmentByID(appointmentID);
            
            payment.setPaymentStatus("COLLECTED");
            payment.setCounterStaff(counterStaff);
            
            appointment.setAppointmentPaymentStatus("PAID");
            
            fh.updateRecord(paymentID, payment.toString());
            fh2.updateRecord(appointmentID, appointment.toString());
            fh3.overwriteRecord(payment);
            
            dh.loadAppointments();
            dh.loadPayments();     
            loadPaymentTable();
            
            tfPaymentID.setText("");
            tfPayAppointmentID.setText("");
            
            JOptionPane.showMessageDialog(null, "Payment Successfully Collected!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }      
    }//GEN-LAST:event_bCollectPaymentActionPerformed

