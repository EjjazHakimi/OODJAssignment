    private User loadCurrentUser() throws FileNotFoundException, IOException {
        String currentUserID = null;
        
        try(BufferedReader br = new BufferedReader(new FileReader("login.txt"))){
            String line = br.readLine();
            
            if(line != null) {
                String [] records = line.split("\\|");
                currentUserID = records [0].trim();      
            }
            
            return dh.getUserByID(currentUserID);
        }
    }
    
    private void loadUserTable() {
        User [] customers = dh.getUserByRole("CUSTOMER");
        
        DefaultTableModel model = (DefaultTableModel) tCustomers.getModel();
        model.setRowCount(0);
        
        for (User u : customers) {
            model.addRow(new Object[]{
                u.getUserID(),
                u.getUsername(),
                u.getPassword(),
                u.getUserRole(),
                "Update",
                "Delete"
            });
        }
    }
    
    private void loadAppointmentTable() throws IOException {
        Appointment [] appointments = dh.getAppointmentByStatus("REQUESTED");
        
        DefaultTableModel model = (DefaultTableModel) tAppointments.getModel();
        model.setRowCount(0);
        
        for (Appointment a : appointments) {
            
            if (a == null) continue;
            
            model.addRow(new Object[] {
                a.getAppointmentID(),
                a.getAppointmentLocation(),
                a.getAppointmentDate(),
                a.getAppointmentStartTime(),
                a.getCustomer().getUsername(),
                "Select"
            });
        }
    }
    
     private void loadPaymentTable() {
        Payment [] payments = dh.getPaymentByStatus("SUBMITTED");
        
        DefaultTableModel model = (DefaultTableModel) tPayments.getModel();
        model.setRowCount(0);
        
        for (Payment p : payments) {
            model.addRow(new Object[]{
                p.getPaymentID(),
                p.getPaymentDate(),
                p.getPaymentAmount(),
                p.getAppointment().getAppointmentID(),
                p.getCustomer().getUsername(),
                "Select"
            });
        }
    }
    
    private void loadTechnicianComboBox() throws IOException {
        
        cbAssignTechnician.removeAllItems();
        
        for (User u : dh.getUserByRole("TECHNICIAN")) {
            cbAssignTechnician.addItem(u.getUsername());
        }
    }
    
