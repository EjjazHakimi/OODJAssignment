    private void bUpdateDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bUpdateDataActionPerformed
        String newUsername = tfUsername.getText();
        String newPassword = tfPassword.getText();
        String currentPassword = tfCurrentPassword.getText();

        try {
            bUpdateData.setEnabled(false);
            User user = loadCurrentUser();

            if(currentPassword.equals(user.getPassword())) {
                user.setUsername(newUsername);
                user.setPassword(newPassword);

                user.toString();

                FileHandler fh = new FileHandler("user.txt");
                fh.updateRecord(tfCurrentID.getText().trim(), user.toString());

                FileHandler fh2 = new FileHandler("login.txt");
                fh2.writeLoginUserRecord(user);
                
                JOptionPane.showMessageDialog(null, "Successfully updated User Profile!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);

                tfUsername.setText(newUsername);
                tfPassword.setText(newPassword);
                tfCurrentPassword.setText("");
                lUser.setText(newUsername);

            } else {
                JOptionPane.showMessageDialog(null, "Current Password is Incorrect", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } finally {
            bUpdateData.setEnabled(true);
        }
    }//GEN-LAST:event_bUpdateDataActionPerformed

    private void bCompleteAppointmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bCompleteAppointmentActionPerformed
        String appointmentID = tfAppointmentID.getText();
        
        if (appointmentID.isBlank()) {
            JOptionPane.showMessageDialog(null, "Please select Appointment!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        FileHandler fh = new FileHandler("appointment.txt");
        
        Appointment appointment = dh.getAppointmentByID(appointmentID);
        
        try {
            appointment.setAppointmentStatus("COMPLETED");
            fh.updateRecord(appointmentID, appointment.toString());
            
            tfAppointmentID.setText("");
            tfAppointmentDate.setText("");
            tfAppointmentType.setText("");
            tfAppointmentStartTime.setText("");
            tfAppointmentEndTime.setText("");
                
            JOptionPane.showMessageDialog(null, "Appointment Completed", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
            
            dh.loadUsers();
            dh.loadAppointments();
            loadAppointmentTable();
            
        } catch (IOException ex) {
            System.getLogger(TechnicianScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }//GEN-LAST:event_bCompleteAppointmentActionPerformed

    private void bExportScheduleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bExportScheduleActionPerformed
        
        FileHandler fh = new FileHandler("myAppointment.txt");

        int rowCount = tAppointments.getRowCount();
        
        try {
            fh.resetFile();
            for(int i = 0; i < rowCount; i++) {
         
                String appointmentID = tAppointments.getValueAt(i, 0).toString();
                Appointment appointment = dh.getAppointmentByID(appointmentID);
                
                if(appointment != null) {
                    fh.writeRecord(appointment);
                }
            }
            eh.appointmentTxtToExcel("myAppointment.txt");
            JOptionPane.showMessageDialog(null, "Schedule Exported Successfully!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException ex) {
            System.getLogger(TechnicianScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_bExportScheduleActionPerformed
    
    private User loadCurrentUser() throws FileNotFoundException, IOException {
        String currentUserID = null;
        
        try(BufferedReader br = new BufferedReader(new FileReader("login.txt"))){
            String line = br.readLine();
            
            if(line != null) {
                String [] records = line.split("\\|");
                currentUserID = records [0].trim();      
            }
            
            return dh.getUserByID(currentUserID);
        }
    }
    
    private void loadAppointmentTable() throws IOException {
        Appointment [] appointments = dh.getAppointmentByStatus("ASSIGNED");
        
        DefaultTableModel model = (DefaultTableModel) tAppointments.getModel();
        model.setRowCount(0);
        
        String technicianID = loadCurrentUser().getUserID();
        
        for (Appointment a : appointments) {
            
            if (a == null) continue;
            
            if (a.getTechnician() == null) continue;

            if (!a.getTechnician().getUserID().equalsIgnoreCase(technicianID)) continue;
            
            model.addRow(new Object[] {
                a.getAppointmentID(),
                a.getAppointmentLocation(),
                a.getCustomer().getUsername(),
                "Select"
            });
        }
    }
    
    private void onStart() throws FileNotFoundException, IOException{
        
        dh.loadUsers();
        dh.loadAppointments();
        User user = loadCurrentUser();
         
        String username = user.getUsername();
        String password = user.getPassword();
        String role = user.getUserRole();
        String id = user.getUserID();
        
        lUser.setText(username);
        tfCurrentID.setText(id);
        tfCurrentRole.setText(role);
        tfUsername.setText(username);
        tfPassword.setText(password);
        loadAppointmentTable();
    }
