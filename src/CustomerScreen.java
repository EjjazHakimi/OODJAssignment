    private void bUpdateDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bUpdateDataActionPerformed
        String newUsername = tfUsername.getText();
        String newPassword = tfPassword.getText();
        String currentPassword = tfCurrentPassword.getText();

        try {
            bUpdateData.setEnabled(false);
            User user = loadCurrentUser();

            if(currentPassword.equals(user.getPassword())) {
                user.setUsername(newUsername);
                user.setPassword(newPassword);

                user.toString();

                FileHandler fh = new FileHandler("user.txt");
                fh.updateRecord(tfCurrentID.getText().trim(), user.toString());

                FileHandler fh2 = new FileHandler("login.txt");
                fh2.writeLoginUserRecord(user);
                
                FileHandler fh3 = new FileHandler("auditLog.txt");
                AuditLog.log(fh3, fh3.generateNextID("AD"), user.getUserID(), "UPDATE", user.getUserID(), "UPDATE USER DETAILS");

                JOptionPane.showMessageDialog(null, "Successfully updated User Profile!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);

                tfUsername.setText(newUsername);
                tfPassword.setText(newPassword);
                tfCurrentPassword.setText("");
                lUser.setText(newUsername);

            } else {
                JOptionPane.showMessageDialog(null, "Current Password is Incorrect", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException ex) {
            System.getLogger(CounterStaffScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } finally {
            bUpdateData.setEnabled(true);
        }
    }//GEN-LAST:event_bUpdateDataActionPerformed

    private void bRequestAppointmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bRequestAppointmentActionPerformed
        FileHandler fh = new FileHandler("appointment.txt");
        FileHandler fh2 = new FileHandler("feedback.txt");
        FileHandler fh3 = new FileHandler("auditLog.txt");
        
        String appointmentLocation = tfAppointmentLocation.getText();
        String customerFeedback = taCustomerFeedback.getText();
        
        Date selectedDate = jdAppointmentDate.getDate();
        String selectedTime = cbAppointmentStartTime.getSelectedItem().toString();
        
        if(appointmentLocation.isBlank()) {
            JOptionPane.showMessageDialog(null, "Appointment Location is Empty!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (selectedDate == null) {
            JOptionPane.showMessageDialog(null, "Appointment Date not Selected!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        } else if (customerFeedback.isBlank()) {
            JOptionPane.showMessageDialog(null, "Customer Comment not Provided!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String appointmentDate = sdf.format(selectedDate);
        
        LocalTime appointmentStartTime = LocalTime.parse(selectedTime);
        LocalDateTime now = LocalDateTime.now();
        
        LocalDate selectedDateCheck = selectedDate.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
        LocalDateTime selectedDateTime = LocalDateTime.of(selectedDateCheck, appointmentStartTime);

        if(selectedDateTime.isBefore(now)) {
            JOptionPane.showMessageDialog(null, "Selected Time has Passed!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            String appointmentID = fh.generateNextID("AP");
            String feedbackID = fh2.generateNextID("FB");
            String appointmentStatus = "REQUESTED";
            String appointmentPaymentStatus = "UNPAID";
            
            Customer customer = (Customer) loadCurrentUser();
            
            Appointment appointment = new Appointment(
                    appointmentID,
                    appointmentLocation,
                    "null",
                    appointmentDate,
                    appointmentStartTime,
                    (LocalTime) null,
                    appointmentStatus,
                    appointmentPaymentStatus,
                    (Technician) null,
                    customer,
                    (CounterStaff) null
                );
            
            Feedback feedback = new Feedback(
                    feedbackID,
                    customerFeedback,
                    "null",
                    appointment,
                    customer,
                    (Technician) null
                );
            
            fh.writeRecord(appointment);
            fh2.writeRecord(feedback);
            
            AuditLog.log(fh3, fh3.generateNextID("AD"), customer.getUserID(), "REQUEST", appointmentID, "REQUEST APPOINTMENT");
            AuditLog.log(fh3, fh3.generateNextID("AD"), customer.getUserID(), "CREATE", appointmentID, "CREATE CUSTOMER FEEDBACK");
            
            dh.loadUsers();
            dh.loadAppointments();
            dh.loadFeedback();
            loadAppointmentTable();
            
            tfAppointmentLocation.setText("");
            taCustomerFeedback.setText("");
            jdAppointmentDate.setDate(null);
            
            JOptionPane.showMessageDialog(null, "Successfully Requested Appointment!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (IOException ex) {
            System.getLogger(CustomerScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }//GEN-LAST:event_bRequestAppointmentActionPerformed

    private void bPayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bPayActionPerformed

        FileHandler fh = new FileHandler("payment.txt");
        FileHandler fh2 = new FileHandler("appointment.txt");
        FileHandler fh3 = new FileHandler("auditLog.txt");
        
        String appointmentID = tfPayAppointmentID.getText();
        
        if(appointmentID.isEmpty()) {
           JOptionPane.showMessageDialog(null, "Please select an appointment!", "ERROR", JOptionPane.ERROR_MESSAGE);
           return;
        }
       
        Double price = Double.parseDouble(tfPayAppointmentPrice.getText());
        String paymentDate = LocalDate.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd"));
        
        try {
            String paymentID = fh.generateNextID("PY");
            Customer customer = (Customer) loadCurrentUser();
            Appointment appointment = dh.getAppointmentByID(appointmentID);
    
            Payment payment = new Payment(
                    paymentID,
                    price,
                    paymentDate,
                    "SUBMITTED",
                    appointment,
                    customer,
                    (CounterStaff) null
                    );
            
            appointment.setAppointmentPaymentStatus("PENDING");
            
            fh.writeRecord(payment);
            fh2.updateRecord(tfPayAppointmentID.getText(), appointment.toString());
            
            AuditLog.log(fh3, fh3.generateNextID("AD"), customer.getUserID(), "SUBMIT", paymentID, "SUBMIT PAYMENT");
            
            dh.loadAppointments();
            dh.loadPayments();
            loadPaymentTable();
            
            tfPayAppointmentID.setText("");
            tfPayAppointmentStartTime.setText("");
            tfPayAppointmentEndTime.setText("");
            tfPayAppointmentPrice.setText("");
            
            JOptionPane.showMessageDialog(null, "Payment Submitted!", "NOTICE", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (IOException ex) {
            System.getLogger(CustomerScreen.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
        
    }//GEN-LAST:event_bPayActionPerformed
    
    private User loadCurrentUser() throws FileNotFoundException, IOException {
        String currentUserID = null;
        
        try(BufferedReader br = new BufferedReader(new FileReader("login.txt"))){
            String line = br.readLine();
            
            if(line != null) {
                String [] records = line.split("\\|");
                currentUserID = records [0].trim();      
            }
            
            return dh.getUserByID(currentUserID);
        }
    }
    
    private void loadAppointmentTable() throws IOException {
        Appointment [] appointments = dh.getAppointmentByStatus("REQUESTED");
        
        DefaultTableModel model = (DefaultTableModel) tAppointments.getModel();
        model.setRowCount(0);
        
        String customerID = loadCurrentUser().getUserID();
        
        for (Appointment a : appointments) {
            
            if (a == null) continue;
            
            if (a.getCustomer() == null) continue;

            if (!a.getCustomer().getUserID().equalsIgnoreCase(customerID)) continue;
            
            model.addRow(new Object[] {
                a.getAppointmentID(),
                a.getAppointmentLocation(),
                a.getAppointmentDate(),
                a.getAppointmentStartTime(),
                "Delete"
            });
        }
    }
    
    private void loadPaymentTable() throws IOException {
        Appointment [] appointments = dh.getAppointmentByPaymentStatus("UNPAID");
        
        DefaultTableModel model = (DefaultTableModel) tPayments.getModel();
        model.setRowCount(0);
        
        String customerID = loadCurrentUser().getUserID();
        
        for (Appointment a : appointments) {
            
            if (a == null) continue;
            
            if (a.getCustomer() == null) continue;

            if (!a.getCustomer().getUserID().equalsIgnoreCase(customerID)) continue;
            
            if (!"CLOSED".equalsIgnoreCase(a.getAppointmentStatus())) continue;
            
            model.addRow(new Object[] {
                a.getAppointmentID(),
                a.getAppointmentDate(),
                a.getAppointmentType(),
                a.getAppointmentLocation(),
                "Select"
            });
        }
    }
    
    private void loadFeedbackTable() throws IOException {
        
        String customerID = loadCurrentUser().getUserID();
        
        Feedback [] feedbacks = dh.getFeedbackByUserID(customerID);
        
        DefaultTableModel model = (DefaultTableModel) tFeedbacks.getModel();
        model.setRowCount(0);
        
        for (Feedback f : feedbacks) {
            
            if (f == null) continue;
            
            if (f.getTechnician() == null) continue;
            
            model.addRow(new Object[] {
                f.getFeedbackID(),
                f.getAppointment().getAppointmentID(),
                f.getTechnician().getUsername(),
                "Select"
            });
        }
    }
    
